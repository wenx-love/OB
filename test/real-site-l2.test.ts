import { describe, it, expect, beforeAll } from 'vitest';
import type { DecoderCapture } from '../src/extension/debugger/capture-engine.js';
import type { ValidationScript } from '../src/core/capture-validation.js';
import { computeScriptHash } from '../src/core/hash-utils.js';
import { CATEGORIES, ORACLE_REASONS, buildOracleReference, bytesOf, compareRun, coverageAcrossRuns, loadFs, persistRun, projectRoot, runPipeline, windowOutcome, writeJsonFile, type BusinessParity, type CompareInput, type CompareResult, type OracleReference, type PipelineRun } from './helpers/real-site-compare.js';

// Phase 4.7 L2: fixed source test on the local-generated seed test/fixtures/real-ob/obfuscated.js.
// The seed is generated by javascript-obfuscator 5.9.0 outside the project. It is NOT a real-site sample (isRealSiteSample=false) and never counts as L1 evidence.
// Reference = independent oracle (node:vm real execution of the unmodified script + @babel/parser). expected.js files of other tools are never used.
// Observed capture records = engine raw records of a PAST run of the real extension in real Chrome on this same fixture
// (test/acceptance/devtools-real-ob-e2e*.json, steps.round1EngineRaw). They are not constructed here and are not a new CDP pause capture.
// Those records carry no CDP script source, so byte identity with the captured script cannot be proven: the source is read from the fixture file, recorded in identity.basis.
// Everything after the records is the production chain: validateCaptures -> dryRunReplacements -> applyVerifiedReplacements.

const SEED_ID = 'l2-real-ob-seed';
const FIXTURE_DIR = 'test/fixtures/real-ob-sites/' + SEED_ID;
const THRESHOLDS: { label: string; suffix: string }[] = [{ label: 'high', suffix: '' }, { label: 'medium', suffix: '-medium' }];

interface RegistrySample { id: string; layer: string; kind: string; isRealSiteSample: boolean; status: string; path: string; plaintextPath: string; sha256: string; plaintextSha256: string; bytes: number; generator: string; generatedAt: string; oraclePolicy?: string }
interface Registry { samples: RegistrySample[]; plannedSamples: { id: string; layer: string; isRealSiteSample: boolean; status: string }[] }
interface Outcome { result: string; title: string }
interface Shared { root: string; registry: Registry; seed: RegistrySample; source: string; plainSource: string; reference: OracleReference; plain: Outcome; obf: Outcome }
interface CaptureFile { file: string; fileSha256: string; total: number; own: DecoderCapture[]; foreign: number }
interface RunState { capture: CaptureFile; pipeline: PipelineRun; input: CompareInput; result: CompareResult }

let shared!: Shared;
const states = new Map<string, RunState>();
const l2Results: CompareResult[] = [];

function isCapture(x: unknown): x is DecoderCapture {
  if (!x || typeof x !== 'object') return false;
  const c = x as Record<string, unknown>;
  const fl = c['functionLocation'] as Record<string, unknown> | undefined;
  return typeof c['key'] === 'string' && typeof c['scriptId'] === 'string' && typeof c['scriptUrl'] === 'string' && typeof c['functionName'] === 'string' && !!fl && typeof fl['lineNumber'] === 'number' && Array.isArray(c['callLocations']) && Array.isArray(c['arguments']) && typeof c['captureStatus'] === 'string' && typeof c['count'] === 'number';
}

async function loadHistoricalCaptures(root: string, suffix: string): Promise<CaptureFile> {
  const fs = await loadFs();
  const file = 'test/acceptance/devtools-real-ob-e2e' + suffix + '.json';
  const text = fs.readFileSync(root + '/' + file, 'utf8');
  const raw: unknown = JSON.parse(text);
  const steps = (raw as { steps?: { round1EngineRaw?: { captures?: unknown } } }).steps;
  const list = steps && steps.round1EngineRaw ? steps.round1EngineRaw.captures : undefined;
  if (!Array.isArray(list)) throw new Error(file + ': steps.round1EngineRaw.captures is not an array');
  const all = list.filter(isCapture);
  if (all.length !== list.length) throw new Error(file + ': some capture records do not have the DecoderCapture shape');
  const own = all.filter((c) => c.scriptUrl.endsWith('/obfuscated.js'));
  if (own.length === 0) throw new Error(file + ': no capture record belongs to /obfuscated.js');
  return { file, fileSha256: await computeScriptHash(text), total: list.length, own, foreign: all.length - own.length };
}

describe('L2 固定源码：本地生成种子样本（不是真实网站样本）', () => {
  beforeAll(async () => {
    const root = await projectRoot();
    const fs = await loadFs();
    const registry: Registry = JSON.parse(fs.readFileSync(root + '/test/fixtures/real-ob-sites/registry.json', 'utf8'));
    const seed = registry.samples.find((s) => s.id === SEED_ID);
    if (!seed) throw new Error('registry has no sample ' + SEED_ID);
    const source = fs.readFileSync(root + '/' + seed.path, 'utf8');
    const plainSource = fs.readFileSync(root + '/' + seed.plaintextPath, 'utf8');
    const reference = await buildOracleReference(source);
    shared = { root, registry, seed, source, plainSource, reference, plain: await windowOutcome(plainSource, 'source.js'), obf: await windowOutcome(source, 'obfuscated.js') };
  }, 60000);

  describe('样本登记与来源', () => {
    it('登记的 SHA-256、字节数与实际文件一致（逐字符，不做换行归一化）', async () => {
      expect(await computeScriptHash(shared.source)).toBe(shared.seed.sha256);
      expect(await computeScriptHash(shared.plainSource)).toBe(shared.seed.plaintextSha256);
      expect(bytesOf(shared.source)).toBe(shared.seed.bytes);
    });

    it('本地生成样本没有被标成真实网站样本；L1 目标站点仍未被登记为可用的通过样本', () => {
      expect(shared.seed.layer).toBe('L2');
      expect(shared.seed.kind).toBe('local-generated');
      expect(shared.seed.isRealSiteSample).toBe(false);
      // 硬规则：本地 javascript-obfuscator 生成的样本永远不得标记为真实网站样本
      expect(shared.registry.samples.every((s) => !(s.kind === 'local-generated' && s.isRealSiteSample))).toBe(true);
      // 真实网站样本只允许是 L1，且必须带 real-site 类型：不允许任何非 L1 样本混入 isRealSiteSample=true
      const realSites = shared.registry.samples.filter((s) => s.isRealSiteSample);
      expect(realSites.every((s) => s.layer === 'L1' && s.kind === 'real-site')).toBe(true);
      // L1 的登记状态是 blocked（跑过但因验证层全部拒绝而未通过），不是任何"通过/可用"状态
      const l1Sample = shared.registry.samples.find((s) => s.layer === 'L1');
      expect(l1Sample?.status).toBe('blocked');
      // planner 里"待用户确认站点"的条目仍未消费：授权边界不变
      const l1 = shared.registry.plannedSamples.find((s) => s.layer === 'L1');
      expect(l1?.status).toBe('blocked-awaiting-user');
      expect(shared.seed.oraclePolicy ?? '').toContain('expected.js');
    });
  });

  describe('真实执行结果与 reference', () => {
    it('混淆脚本与手写明文脚本在 node:vm 里的执行结果一致（verify-real-ob-sample 口径：__obResult 与 title）', () => {
      expect(shared.obf.result).not.toBe('undefined');
      expect(shared.obf.result).toBe(shared.plain.result);
      expect(shared.obf.title).toBe(shared.plain.title);
    });

    it('独立 oracle 的参考非空：有可确定位置，也有被标为不可确定的位置（旋转 IIFE 内的调用）', () => {
      const sites = shared.reference.sites;
      expect(shared.reference.rotationRange).not.toBeNull();
      expect(sites.filter((s) => s.determinate).length).toBeGreaterThan(0);
      expect(sites.filter((s) => !s.determinate).length).toBeGreaterThan(0);
      for (const s of sites) {
        if (s.determinate) expect(typeof s.value).toBe('string');
        expect(s.reason.length).toBeGreaterThan(0);
      }
      const keys = new Set(sites.map((s) => s.position.lineNumber + ':' + s.position.columnNumber));
      expect(keys.size).toBe(sites.length);
      expect(shared.reference.callableHexFunctions.length).toBeGreaterThan(0);
    });
  });

  describe.each(THRESHOLDS)('历史真实 Chrome 捕获记录 + 生产链路（$label 门槛）', ({ label, suffix }) => {
    const st = (): RunState => {
      const s = states.get(label);
      if (!s) throw new Error('run state missing for ' + label);
      return s;
    };

    beforeAll(async () => {
      const capture = await loadHistoricalCaptures(shared.root, suffix);
      const scriptIds = Array.from(new Set(capture.own.map((c) => c.scriptId)));
      const scripts: ValidationScript[] = scriptIds.map((id) => ({ scriptId: id, source: shared.source }));
      const pipeline = await runPipeline(capture.own, scripts);
      const observedSha = await computeScriptHash(shared.source);
      const after = Object.values(pipeline.afterHashes).find((h) => h !== observedSha) ?? observedSha;
      let parity: BusinessParity = 'not-evaluated';
      if (pipeline.applied.length > 0) {
        parity = 'pass';
        for (const a of pipeline.applies) {
          const o = await windowOutcome(a.apply.code, 'recovered.js');
          if (o.result !== shared.plain.result || o.title !== shared.plain.title) parity = 'fail';
        }
      }
      const input: CompareInput = {
        runId: 'run-' + label,
        sample: { id: SEED_ID, layer: 'L2', kind: 'local-generated', isRealSiteSample: false, title: 'javascript-obfuscator 5.9.0 seed, capture threshold ' + label },
        reference: { capturedBy: 'test-oracle', method: 'node:vm execution of the unmodified script + @babel/parser AST (test/helpers/real-site-compare.ts buildOracleReference)', note: 'independent of OB-Recover: no src analysis code is used; expected.js of other tools is not used' },
        observed: { capturedBy: 'ob-recover', method: 'historical-real-chrome-capture-engine-records (' + capture.file + ' steps.round1EngineRaw) re-validated offline: validateCaptures -> dryRunReplacements -> applyVerifiedReplacements', note: 'not a new CDP pause capture and not constructed by this test; engine raw records filtered by scriptUrl suffix /obfuscated.js' },
        referenceSites: shared.reference.sites,
        identity: { referenceSha256: shared.seed.sha256, observedSha256: observedSha, afterApplySha256: after, basis: 'ValidationScript.source is read from the fixture file: the historical records carry no CDP script source, so byte identity with the originally captured script is not proven; call positions are checked by the AST locator instead' },
        applied: pipeline.applied,
        rejections: pipeline.rejections,
        businessParity: parity,
      };
      const result = compareRun(input);
      states.set(label, { capture, pipeline, input, result });
      l2Results.push(result);

      await persistRun(shared.root + '/' + FIXTURE_DIR + '/run-' + label, {
        meta: { siteId: SEED_ID, runId: 'run-' + label, layer: 'L2', kind: 'local-generated', isRealSiteSample: false, url: null, sha256: shared.seed.sha256, bytes: shared.seed.bytes, fetchedAt: null, fetchedAtNote: 'not fetched: local-generated fixture, generatedAt ' + shared.seed.generatedAt, capturedBy: 'n/a-fixture-file', tooling: shared.seed.generator + ' (generator, outside the project)', captureThreshold: label },
        reference: {
          'call-sites.json': { capturedBy: 'test-oracle', method: input.reference.method, note: input.reference.note, rotationRange: shared.reference.rotationRange, reasonLegend: ORACLE_REASONS, sites: shared.reference.sites },
          'decoders.json': { capturedBy: 'test-oracle', method: input.reference.method, topLevelHexFunctions: shared.reference.topLevelHexFunctions, callableHexFunctions: shared.reference.callableHexFunctions },
        },
        observed: {
          'apply.json': { capturedBy: 'ob-recover', method: input.observed.method, note: input.observed.note, captureSource: { file: capture.file, fileSha256: capture.fileSha256, totalRecords: capture.total, recordsUsed: capture.own.length, foreignRecordsExcluded: capture.foreign }, scriptIds, validation: pipeline.report.summary, dryRun: pipeline.dry.summary, applyStats: pipeline.applies.map((a) => ({ scriptId: a.scriptId, stats: a.apply.stats })), applied: pipeline.applied },
        },
        compare: result,
      });
    }, 120000);

    it('硬性条件：误替换 0，原始源码字节三处一致，Safe Rejection Rate 与 Precision 只能是 100% 或 n/a', () => {
      const { result } = st();
      expect(result.metrics.falseReplacement).toBe(0);
      expect(result.counts['false-replacement']).toBe(0);
      expect(result.metrics.sourceIntegrity).toBe(true);
      expect(result.identity.referenceSha256).toBe(result.identity.observedSha256);
      expect(result.identity.observedSha256).toBe(result.identity.afterApplySha256);
      expect([1, 'n/a']).toContain(result.metrics.safeRejectionRate);
      expect([1, 'n/a']).toContain(result.metrics.precision);
      expect(['pass', 'inconclusive']).toContain(result.verdict);
    });

    it('五类互斥且穷尽；没有版本不一致；每个应用过的字面量都等于独立 oracle 的值', () => {
      const { result, pipeline } = st();
      expect(result.exhaustive).toBe(true);
      expect(CATEGORIES.reduce((n, c) => n + result.counts[c], 0)).toBe(result.sites.length);
      expect(result.counts['version-mismatch']).toBe(0);
      expect(result.counts['correct-replacement']).toBe(pipeline.applied.length);
      for (const s of result.sites) expect(CATEGORIES).toContain(s.category);
    });

    it('未还原的可确定位置（Unresolved）都带原因：拒绝码，或明确写明没有任何记录覆盖该位置', () => {
      const { result } = st();
      for (const s of result.sites.filter((x) => x.category === 'insufficient-evidence')) {
        expect(s.rejectionCodes.length > 0 || (s.note ?? '').length > 0).toBe(true);
      }
    });

    it('业务逻辑：有替换发生时，还原后的脚本在 node:vm 里的 __obResult 与 title 与明文脚本一致；没有替换时记 not-evaluated，不记通过', () => {
      const { result, pipeline } = st();
      if (pipeline.applied.length > 0) expect(result.metrics.businessParity).toBe('pass');
      else expect(result.metrics.businessParity).toBe('not-evaluated');
    });

    it('compare.json 已落盘并可回读，保留样本身份、来源、三处哈希和完整五类计数', async () => {
      const { result } = st();
      const fs = await loadFs();
      const back = JSON.parse(fs.readFileSync(shared.root + '/' + FIXTURE_DIR + '/run-' + label + '/compare.json', 'utf8'));
      expect(back).toEqual(JSON.parse(JSON.stringify(result)));
      expect(back.sample.id).toBe(SEED_ID);
      expect(back.sample.isRealSiteSample).toBe(false);
      expect(back.provenance.reference.capturedBy).toBe('test-oracle');
      expect(back.provenance.observed.capturedBy).toBe('ob-recover');
      expect(back.identity.referenceSha256).toBe(shared.seed.sha256);
      expect(Object.keys(back.counts).sort()).toEqual([...CATEGORIES].sort());
    });

    it('对照模块在真实数据上能发现问题（负向对照）：版本不一致、源码被改、伪造的错误替换', () => {
      const { input } = st();
      const other = shared.seed.sha256.slice(0, 63) + (shared.seed.sha256.endsWith('0') ? '1' : '0');
      const vm = compareRun({ ...input, identity: { ...input.identity, referenceSha256: other } });
      expect(vm.verdict).toBe('version-mismatch');
      expect(vm.counts['version-mismatch']).toBe(shared.reference.sites.length);
      expect(vm.metrics.precision).toBe('n/a');
      const mutated = compareRun({ ...input, identity: { ...input.identity, afterApplySha256: other } });
      expect(mutated.metrics.sourceIntegrity).toBe(false);
      expect(mutated.verdict).toBe('not-pass');
      const target = shared.reference.sites.find((s) => !s.determinate);
      if (!target) throw new Error('reference has no indeterminate site to forge a replacement on');
      const forged = compareRun({ ...input, applied: [...input.applied, { position: target.position, original: target.callText, replaced: JSON.stringify('forged') }] });
      expect(forged.counts['false-replacement']).toBeGreaterThanOrEqual(1);
      expect(forged.hardConditions.falseReplacementIsZero).toBe(false);
      expect(forged.verdict).toBe('not-pass');
    });

    it('可重复：同样的输入再比一次，compare 结果逐字段相同', () => {
      const { input, result } = st();
      expect(compareRun(input)).toEqual(result);
    });
  });

  describe('L2 汇总', () => {
    it('High 与 Medium 各自保留独立的正式指标；跨配置结果只是补充覆盖统计，不带 verdict、硬性条件和任何比率；写出 summary.json', async () => {
      expect(l2Results).toHaveLength(THRESHOLDS.length);
      for (const r of l2Results) {
        expect(r.exhaustive).toBe(true);
        expect(r.metrics.falseReplacement).toBe(0);
        expect(r.metrics.sourceIntegrity).toBe(true);
        expect(r.counts['version-mismatch']).toBe(0);
        expect(r.metrics.versionMismatch.totalRuns).toBe(1);
      }
      const coverage = coverageAcrossRuns(l2Results, shared.reference.sites);
      expect(coverage.isRunResult).toBe(false);
      expect(coverage.referencePositions).toBe(shared.reference.sites.length);
      for (const key of ['verdict', 'hardConditions', 'identity', 'metrics', 'counts', 'detail', 'precision', 'recall', 'safeRejectionRate']) expect(Object.keys(coverage)).not.toContain(key);
      expect(coverage.restoredByAtLeastOneRun).toBeGreaterThanOrEqual(Math.max(...l2Results.map((r) => r.detail.tp)));
      expect(coverage.restoredByAtLeastOneRun).toBeLessThanOrEqual(coverage.determinatePositions);
      expect(coverage.restoredByAllRuns).toBeLessThanOrEqual(coverage.restoredByAtLeastOneRun);
      expect(coverage.restoredByAtLeastOneRun + coverage.restoredByNoRun).toBe(coverage.determinatePositions);
      for (const r of l2Results) expect(coverage.falseReplacementCountPerRun[r.runId]).toBe(r.counts['false-replacement']);
      expect(coverage.replacedIndeterminatePositionsInAnyRun).toBe(0);
      await writeJsonFile(shared.root + '/' + FIXTURE_DIR + '/summary.json', {
        schema: 'ob-recover.real-site-summary/2',
        layer: 'L2',
        sample: SEED_ID,
        isRealSiteSample: false,
        formalPerConfiguration: l2Results.map((r) => ({ configuration: r.runId.replace('run-', ''), runId: r.runId, compareFile: FIXTURE_DIR + '/' + r.runId + '/compare.json', provenance: r.provenance, identity: r.identity, counts: r.counts, detail: r.detail, metrics: r.metrics, hardConditions: r.hardConditions, verdict: r.verdict, exhaustive: r.exhaustive })),
        supplementaryCoverage: coverage,
        notes: ['formalPerConfiguration is the only place that reports the performance of a capture threshold: each entry is the unmodified compare result of that configuration', 'supplementaryCoverage is a cross-configuration view over the SAME reference positions; it is not the result of any configuration and carries no verdict, no hard conditions and no Precision, Recall or Safe Rejection Rate', 'L2 only proves the comparison system and the pipeline on one fixed local-generated sample; it is not L1 evidence and does not make Phase 4.7 pass', 'the seed is generated by javascript-obfuscator outside the project and is never labelled a real-site sample', 'Recall is reported as observed; the targets of plan 8.4 are observation targets, never a reason to relax a safety rule'],
      });
    });
  });
});
